import argparse
import csv
import statistics
import time
from pathlib import Path
from typing import List

import numpy as np

from TTS.api import TTS


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Benchmark latency and RTF for a trained TTS checkpoint.")
    parser.add_argument("--model-path", required=True, help="Path to best_model.pth or checkpoint file.")
    parser.add_argument("--config-path", required=True, help="Path to config.json generated by training.")
    parser.add_argument("--gpu", action="store_true", help="Run inference on GPU.")
    parser.add_argument("--speaker", default=None, help="Speaker name for multi-speaker model.")
    parser.add_argument("--language", default=None, help="Language name for multilingual model.")
    parser.add_argument("--text", default=None, help="Single text to benchmark.")
    parser.add_argument("--texts-file", default=None, help="Text file containing one sentence per line.")
    parser.add_argument("--repeats", type=int, default=1, help="Number of repeats per sentence.")
    parser.add_argument("--warmup-runs", type=int, default=1, help="Warmup inference runs.")
    parser.add_argument("--metrics-out", default=None, help="Optional CSV path to write per-run metrics.")
    return parser.parse_args()


def load_sentences(args: argparse.Namespace) -> List[str]:
    if args.text:
        return [args.text.strip()]

    if args.texts_file:
        text_file = Path(args.texts_file).expanduser().resolve()
        if not text_file.exists():
            raise FileNotFoundError(f"Text file not found: {text_file}")
        with text_file.open("r", encoding="utf-8") as handle:
            lines = [line.strip() for line in handle.readlines()]
        lines = [line for line in lines if line]
        if not lines:
            raise ValueError("No non-empty lines found in texts file.")
        return lines

    return [
        "xin chao, day la cau kiem tra toc do mo hinh.",
        "hom nay troi dep va chung ta dang thu nghiem text to speech.",
        "he thong can dat latency thap hon hai giay tren mot cau ngan.",
    ]


def resolve_speaker(tts: TTS, speaker_arg: str) -> str:
    if not tts.is_multi_speaker:
        return None
    if speaker_arg:
        return speaker_arg
    if tts.speakers and len(tts.speakers) > 0:
        return tts.speakers[0]
    raise ValueError("Model is multi-speaker but no speaker could be resolved.")


def resolve_language(tts: TTS, language_arg: str) -> str:
    if not tts.is_multi_lingual:
        return None
    if language_arg:
        return language_arg
    if tts.languages and len(tts.languages) > 0:
        return tts.languages[0]
    raise ValueError("Model is multi-lingual but no language could be resolved.")


def main() -> None:
    args = parse_args()

    model_path = Path(args.model_path).expanduser().resolve()
    config_path = Path(args.config_path).expanduser().resolve()
    if not model_path.exists():
        raise FileNotFoundError(f"Model checkpoint not found: {model_path}")
    if not config_path.exists():
        raise FileNotFoundError(f"Config file not found: {config_path}")

    sentences = load_sentences(args)

    tts = TTS(model_path=str(model_path), config_path=str(config_path), gpu=args.gpu)
    speaker = resolve_speaker(tts, args.speaker)
    language = resolve_language(tts, args.language)

    for _ in range(max(0, args.warmup_runs)):
        _ = tts.tts(
            text=sentences[0],
            speaker=speaker,
            language=language,
            split_sentences=False,
        )

    sample_rate = tts.synthesizer.output_sample_rate
    metrics = []

    for sentence in sentences:
        for repeat_idx in range(args.repeats):
            start_time = time.perf_counter()
            wav = tts.tts(
                text=sentence,
                speaker=speaker,
                language=language,
                split_sentences=False,
            )
            latency = time.perf_counter() - start_time
            wav_np = np.array(wav, dtype=np.float32)
            audio_seconds = len(wav_np) / float(sample_rate)
            rtf = latency / max(audio_seconds, 1e-6)
            metrics.append(
                {
                    "text": sentence,
                    "repeat": repeat_idx,
                    "latency_sec": latency,
                    "audio_sec": audio_seconds,
                    "rtf": rtf,
                }
            )

    latencies = [row["latency_sec"] for row in metrics]
    rtfs = [row["rtf"] for row in metrics]

    print(f"Runs: {len(metrics)}")
    print(f"Speaker: {speaker}")
    print(f"Language: {language}")
    print(f"Latency mean: {statistics.mean(latencies):.4f} sec")
    print(f"Latency p95: {np.percentile(latencies, 95):.4f} sec")
    print(f"RTF mean: {statistics.mean(rtfs):.4f}")
    print(f"RTF p95: {np.percentile(rtfs, 95):.4f}")

    if args.metrics_out:
        metrics_path = Path(args.metrics_out).expanduser().resolve()
        metrics_path.parent.mkdir(parents=True, exist_ok=True)
        with metrics_path.open("w", encoding="utf-8", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=["text", "repeat", "latency_sec", "audio_sec", "rtf"])
            writer.writeheader()
            writer.writerows(metrics)
        print(f"Wrote metrics: {metrics_path}")


if __name__ == "__main__":
    main()
